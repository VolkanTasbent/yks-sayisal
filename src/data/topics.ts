export type ExamId = "tyt" | "ayt";

export type Topic = {
  id: string;
  name: string;
};

export type Subject = {
  id: string;
  exam: ExamId;
  name: string;
  weight: string;
  color: string;
  note?: string;
  topics: Topic[];
};

const TR_MAP: Record<string, string> = {
  ç: "c",
  ğ: "g",
  ı: "i",
  ö: "o",
  ş: "s",
  ü: "u",
  Ç: "c",
  Ğ: "g",
  İ: "i",
  I: "i",
  Ö: "o",
  Ş: "s",
  Ü: "u",
};

function slugify(value: string): string {
  return value
    .replace(/[çğıöşüÇĞİIÖŞÜ]/g, (char) => TR_MAP[char] ?? char)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function topicList(subjectId: string, names: string[]): Topic[] {
  return names.map((name) => ({
    id: `${subjectId}-${slugify(name)}`,
    name,
  }));
}

